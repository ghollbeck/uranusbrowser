// Writes chromium/shell/ui/logo.ts from the two SVG masters in this folder: the logo as an inline
// tile (cropped to the tile) and the one-colour mark. Run by build-logo.sh.
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8');
const squash = (svg) =>
  svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<title>[^<]*<\/title>/g, '')
    .replace(/>\s+</g, '><')
    .trim();

const TILE_BOX = '46 50 932 924'; // the tile's rect in anus-logo.svg
let tile = squash(read('anus-logo.svg')).replace(/viewBox="[^"]*" width="1024" height="1024"/, `viewBox="${TILE_BOX}"`);
const mark = squash(read('anus-mark.svg')).replace(/ width="\d+" height="\d+"/, '');
if (!tile.includes(`viewBox="${TILE_BOX}"`) || !tile.includes('<rect x="46" y="50" width="932" height="924"')) throw new Error('anus-logo.svg changed shape; update build-shell-logo.mjs');

const out = `// Generated by chromium/branding/logo/build-logo.sh from anus-logo.svg and anus-mark.svg. Do not edit.

/** The Uranus Browser logo: a flat white tile with the black arrow. Fills its box. */
export const LOGO_TILE = '${tile}';

/** The arrow alone, in currentColor. */
export const LOGO_MARK = '${mark}';
`;
fs.writeFileSync(path.join(here, '../../shell/ui/logo.ts'), out);
console.log('made chromium/shell/ui/logo.ts');
